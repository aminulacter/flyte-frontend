/**
 * Extracts technology stack cards from app/content.js → lib/hire/techStacks.js
 */
import fs from "node:fs";
import path from "node:path";
import { parse } from "node-html-parser";

const SRC = path.resolve("app/content.js");
const OUT = path.resolve("lib/hire/techStacks.js");

const HOVER_COLORS = {
  frontend: "#006FBA",
  backend: "#65308C",
  mobileDevelopment: "#007F5F",
  qualityAssurance: "#9A341D",
  devOps: "#014F43",
  aiML: "#2C3E50",
};

const SLUG_MAP = {
  "frontend-developer": "frontend",
  "backend-developer": "backend",
  "mobile-app-developer": "mobileDevelopment",
  "qa-engineer": "qualityAssurance",
  "devops-engineer": "devOps",
  "ai-ml-developer": "aiML",
};

function readHtml(file) {
  const mod = fs.readFileSync(file, "utf8");
  const match = mod.match(/export default "([\s\S]*)";?\s*$/);
  if (!match) throw new Error(`Could not read ${file}`);
  return match[1]
    .replace(/\\n/g, "\n")
    .replace(/\\"/g, '"')
    .replace(/\\'/g, "'")
    .replace(/\\u([\dA-Fa-f]{4})/g, (_, h) => String.fromCharCode(parseInt(h, 16)));
}

function text(el) {
  return el?.text?.trim().replace(/\s+/g, " ") || "";
}

const html = readHtml(SRC);
const root = parse(html);
const techSection = root.querySelector("[style*='operationsBg.png']");
const stacks = {};

for (const card of techSection?.querySelectorAll("a[href^='/hire/']") || []) {
  const href = card.getAttribute("href") || "";
  const slug = href.replace("/hire/", "");
  const key = SLUG_MAP[slug];
  if (!key) continue;
  const techs = [];
  for (const tag of card.querySelectorAll(".rounded-\\[15px\\]")) {
    const img = tag.querySelector("img");
    techs.push({
      name: text(tag.querySelector("div:last-child")),
      image: img?.getAttribute("src") || "",
    });
  }
  stacks[key] = {
    hireLinkName: slug,
    hoverColor: HOVER_COLORS[key],
    title: text(card.querySelector(".font-bold")),
    description: text(card.querySelector(".text-xs")),
    technologies: techs,
  };
}

const order = ["frontend", "backend", "mobileDevelopment", "qualityAssurance", "devOps", "aiML"];
const ordered = order.map((k) => stacks[k]).filter(Boolean);

const out = `/** Auto-generated by scripts/extract-tech-stacks.mjs */
export const TECH_STACK_CARDS = ${JSON.stringify(ordered, null, 2)};
`;

fs.writeFileSync(OUT, out);
console.log("Wrote", OUT, `(${ordered.length} cards)`);
