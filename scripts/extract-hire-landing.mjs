/**
 * Parses app/hire/content.js into lib/hire/landing.js
 */
import fs from "node:fs";
import path from "node:path";
import { parse } from "node-html-parser";

const SRC = path.resolve("app/hire/content.js");
const OUT = path.resolve("lib/hire/landing.js");

function readHtml(file) {
  const mod = fs.readFileSync(file, "utf8");
  const match = mod.match(/export default "([\s\S]*)";?\s*$/);
  if (!match) throw new Error(`Could not read ${file}`);
  return match[1]
    .replace(/\\n/g, "\n")
    .replace(/\\"/g, '"')
    .replace(/\\'/g, "'")
    .replace(/\\u([\dA-Fa-f]{4})/g, (_, h) => String.fromCharCode(parseInt(h, 16)));
}

function text(el) {
  return el?.text?.trim().replace(/\s+/g, " ") || "";
}

const html = readHtml(SRC);
const root = parse(html);

const heroBlock = root.querySelector(".pt-10.lg\\:pt-44");
const hero = {
  eyebrow: text(heroBlock?.querySelector("h4")),
  title: text(heroBlock?.querySelector("h1")),
  description: text(heroBlock?.querySelector("p")),
  image: heroBlock?.getAttribute("style")?.match(/url\(([^)]+)\)/)?.[1] || "",
  ctaLabel: text(heroBlock?.querySelector("a")),
  ctaHref: heroBlock?.querySelector("a")?.getAttribute("href") || "/hire/application-form",
};

const advantagesTitle = text(
  [...root.querySelectorAll("h2")].find((h) => text(h).includes("Advantages of the Dedicated"))
);

const advantages = [];
const advSection = [...root.querySelectorAll("h2")]
  .find((h) => text(h).includes("Advantages of the Dedicated"))
  ?.closest("div")?.parentNode;
for (const card of advSection?.querySelectorAll("div") || []) {
  const h4 = card.querySelector("h4");
  const p = card.querySelector("p.text-gray-600");
  if (!h4 || text(h4).includes("Dedicated Developers")) continue;
  if (advantages.some((a) => a.title === text(h4))) continue;
  advantages.push({ title: text(h4), description: text(p) });
}

const ctaCard = advSection?.querySelector(".bg-\\[\\#31323c\\]");
const buildTeamCta = {
  title: text(ctaCard?.querySelector("h2")),
  description: text(ctaCard?.querySelector("p")),
  ctaLabel: text(ctaCard?.querySelector("a")),
  ctaHref: ctaCard?.querySelector("a")?.getAttribute("href") || "/hire/application-form",
};

const scenarios = [];
const scenarioGrid = root.querySelectorAll(".bg-\\[\\#FAFAFA\\] .grid")[0];
for (const card of scenarioGrid?.querySelectorAll(".rounded-2xl") || []) {
  const tag = text(card.querySelector("span"));
  const h4 = card.querySelector("h4");
  const p = card.querySelector("p");
  const bullets = [];
  for (const row of card.querySelectorAll(".bg-white.rounded-\\[15px\\] .text-xs")) {
    bullets.push(text(row));
  }
  scenarios.push({
    tag,
    title: text(h4),
    description: text(p),
    bullets,
    backgroundImage: card.getAttribute("style")?.match(/url\(([^)]+)\)/)?.[1] || "",
  });
}

const scenariosTitle = text(root.querySelector(".bg-\\[\\#FAFAFA\\] h2"));

const out = `/** Auto-generated by scripts/extract-hire-landing.mjs */
export const HIRE_LANDING_HERO = ${JSON.stringify(hero, null, 2)};

export const HIRE_ADVANTAGES_TITLE = ${JSON.stringify(advantagesTitle)};

export const HIRE_ADVANTAGES = ${JSON.stringify(advantages, null, 2)};

export const HIRE_BUILD_TEAM_CTA = ${JSON.stringify(buildTeamCta, null, 2)};

export const HIRE_SCENARIOS_TITLE = ${JSON.stringify(scenariosTitle)};

export const HIRE_SCENARIOS = ${JSON.stringify(scenarios, null, 2)};
`;

fs.writeFileSync(OUT, out);
console.log("Wrote", OUT);
